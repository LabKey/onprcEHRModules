-- Create temporary report processing table
CREATE TABLE IF NOT EXISTS onprc_ehr.Rpt_TempJmacDate(
    searchid integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) NOT NULL,
    animalid varchar(200) NULL,
    JBGRemovalDate timestamp(0) NULL,
    JBGActualRemovalDate timestamp(0) NULL,
    CONSTRAINT PK_Rpt_TempJmacDate PRIMARY KEY (searchid)
);

-- Create permanent removal date table
CREATE TABLE IF NOT EXISTS onprc_ehr.JmacRemovalDate(
    searchid integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) NOT NULL,
    Id varchar(100) NULL,
    JBGRemovalDate timestamp(0) NULL,
    JBGActualRemovalDate timestamp(0) NULL,
    DaysDiff double precision NULL,
    reason varchar(100) NULL,
    CONSTRAINT PK_JmacRemovalDate PRIMARY KEY (searchid)
);

