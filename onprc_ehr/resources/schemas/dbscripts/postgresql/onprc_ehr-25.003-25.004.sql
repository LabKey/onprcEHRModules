-- Create the conversion mapping table
CREATE TABLE onprc_ehr.RequirementName_Convert (
    searchid integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) NOT NULL,
    PreviousDesignation varchar(255) NULL,
    afterName varchar(255) NULL,
    FileName varchar(1000) NULL,
    CONSTRAINT PK_RequirementName_Convert PRIMARY KEY (searchid) -- TODO: Note - no PK on SQL Server
);

/*
**
**	 Created by	Date		Comment
**
**
